"""Generate a tiny SYNTHETIC dataset in xBD format to smoke-test the pipeline without downloading xBD.

NOT for results: buildings are coloured rectangles and "damage" is drawn rubble. Real experiments use xBD.
python scripts/make_synthetic_sample.py --out data/synthetic_xbd --tiles 8
"""
import argparse
import json
import random
from pathlib import Path

import numpy as np
from PIL import Image

LABELS = ["no-damage", "minor-damage", "major-damage", "destroyed"]
LABEL_WEIGHTS = [0.55, 0.2, 0.15, 0.1]          # imbalanced, like real disasters
BASE_LON, BASE_LAT, DEG_PER_PX = 85.3240, 27.7172, 3e-6


def rubble(h, w, rng):
    return rng.integers(60, 140, size=(h, w, 3)).astype(np.uint8) * np.array([1.0, 0.85, 0.65])


def make_tile(idx, size, n_buildings, rng, pyrng, disaster):
    pre = np.zeros((size, size, 3), np.float32)
    pre[:] = (70, 110, 60)
    pre += rng.normal(0, 12, pre.shape)
    occupied, feats_xy, feats_ll = [], [], []
    for _ in range(n_buildings * 10):
        if len(feats_xy) == n_buildings:
            break
        w, h = pyrng.randint(14, 30), pyrng.randint(14, 30)
        x, y = pyrng.randint(4, size - w - 4), pyrng.randint(4, size - h - 4)
        if any(not (x + w + 4 < ox or ox + ow + 4 < x or y + h + 4 < oy or oy + oh + 4 < y) for ox, oy, ow, oh in occupied):
            continue
        occupied.append((x, y, w, h))
        uid = f"{disaster}-{idx:04d}-{len(feats_xy):03d}"
        pre[y:y + h, x:x + w] = pyrng.choice([(170, 170, 175), (150, 120, 100), (190, 185, 170)])
        label = pyrng.choices(LABELS, LABEL_WEIGHTS)[0]
        poly_xy = f"POLYGON (({x} {y}, {x + w} {y}, {x + w} {y + h}, {x} {y + h}, {x} {y}))"
        lon0, lat0 = BASE_LON + (idx * size + x) * DEG_PER_PX, BASE_LAT - y * DEG_PER_PX
        lon1, lat1 = lon0 + w * DEG_PER_PX, lat0 - h * DEG_PER_PX
        poly_ll = f"POLYGON (({lon0} {lat0}, {lon1} {lat0}, {lon1} {lat1}, {lon0} {lat1}, {lon0} {lat0}))"
        feats_xy.append({"properties": {"feature_type": "building", "subtype": label, "uid": uid}, "wkt": poly_xy})
        feats_ll.append({"properties": {"feature_type": "building", "subtype": label, "uid": uid}, "wkt": poly_ll})
    post = pre.copy()
    for (x, y, w, h), f in zip(occupied, feats_xy):
        label = f["properties"]["subtype"]
        if label == "minor-damage":
            for _ in range(3):
                cx, cy = x + pyrng.randint(0, w - 4), y + pyrng.randint(0, h - 4)
                post[cy:cy + 4, cx:cx + 4] = (60, 50, 40)
        elif label == "major-damage":
            post[y:y + h // 2, x:x + w] = rubble(h // 2, w, rng)
        elif label == "destroyed":
            region = post[max(y - 3, 0):y + h + 3, max(x - 3, 0):x + w + 3]
            region[:] = rubble(region.shape[0], region.shape[1], rng)
    post += rng.normal(0, 6, post.shape)                 # different acquisition: slight noise/brightness shift
    return [Image.fromarray(np.clip(a, 0, 255).astype(np.uint8)) for a in (pre, post)], feats_xy, feats_ll


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="data/synthetic_xbd")
    ap.add_argument("--tiles", type=int, default=8)
    ap.add_argument("--size", type=int, default=256)
    ap.add_argument("--buildings", type=int, default=24)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args(argv)
    out, rng, pyrng, disaster = Path(a.out), np.random.default_rng(a.seed), random.Random(a.seed), "synthetic-quake"
    (out / "images").mkdir(parents=True, exist_ok=True)
    (out / "labels").mkdir(parents=True, exist_ok=True)
    for i in range(a.tiles):
        (pre, post), xy, ll = make_tile(i, a.size, a.buildings, rng, pyrng, disaster)
        stem = f"{disaster}_{i:08d}"
        pre.save(out / "images" / f"{stem}_pre_disaster.png")
        post.save(out / "images" / f"{stem}_post_disaster.png")
        meta = {"disaster": disaster, "disaster_type": "earthquake", "width": a.size, "height": a.size, "img_name": f"{stem}_post_disaster.png"}
        (out / "labels" / f"{stem}_post_disaster.json").write_text(json.dumps({"features": {"lng_lat": ll, "xy": xy}, "metadata": meta}))
        pre_feats = [{"properties": {"feature_type": "building", "uid": f["properties"]["uid"]}, "wkt": f["wkt"]} for f in xy]
        (out / "labels" / f"{stem}_pre_disaster.json").write_text(json.dumps({"features": {"lng_lat": [], "xy": pre_feats},
                                                                              "metadata": {**meta, "img_name": f"{stem}_pre_disaster.png"}}))
    (out / "README.txt").write_text("SYNTHETIC test data generated by scripts/make_synthetic_sample.py. Not real imagery; never report results on it.\n")
    print(f"wrote {a.tiles} synthetic tiles to {out}")


if __name__ == "__main__":
    main()
